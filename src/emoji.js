// 把分类摊平成「名字 → emoji」，后写的分类不覆盖先写的。
const NAMES = {};
for (const group of Object.values(CATALOG)) for (const [name, emoji] of Object.entries(group)) NAMES[name] = emoji;

const ALIASES = {
  '[ok]':'OK', '抠鼻屎':'抠鼻', '微笑的脸':'微笑', '大笑的脸':'大笑', '流汗':'汗',
  '爱心眼':'❤️', '色':'喜欢', '强':'点赞', '弱':'踩', '月亮':'晚安', '太阳':'早安',
  '吐舌':'调皮', '憨笑':'笑哭', '阴险':'坏笑', '拍头':'摸头', '左哼哼':'撇嘴', '右哼哼':'撇嘴',
};
const FACE_MARKUP = /<faceType=\d+,faceId="?[\w-]+"?(?:,ext="([^"]*)")?\s*\/?>/g;
const MAX_PER_MESSAGE = 6;

export function faceName(ext) {
  if (typeof ext !== 'string' || !ext || ext.length > 2000) return '';
  try {
    const decoded = Buffer.from(ext, 'base64').toString('utf8');
    const parsed = JSON.parse(decoded);
    const text = typeof parsed?.text === 'string' ? parsed.text.trim() : '';
    return text.length <= 40 ? text : '';
  } catch { return ''; }
}
export function faceToLabel(emoji, name) {
  const clean = String(name || '').trim();
  const mapped = !emoji && clean ? NAMES[ALIASES[clean] || clean] : emoji;
  if (mapped) return mapped;
  return clean ? `[表情:${clean}]` : '[表情]';
}
// 入站：把 QQ 原生表情标记换成可读形式，避免把 base64 标记塞进模型上下文。
export function facesToText(text) {
  if (typeof text !== 'string' || !text.includes('<faceType')) return typeof text === 'string' ? text : '';
  return text.replace(FACE_MARKUP, (_match, ext) => faceToLabel('', faceName(ext)));
}
// 出站：模型可能残留标记或写出 [微笑]，统一换成 Unicode emoji；不认识的名字保持原样。
export function toUnicodeEmoji(text) {
  if (typeof text !== 'string' || !text) return '';
  let out = text.replace(FACE_MARKUP, (_match, ext) => faceToLabel('', faceName(ext)));
  let used = 0;
  out = out.replace(/\[([^\[\]\n]{1,12})\]/g, (match, raw) => {
    const name = raw.trim();
    if (used >= MAX_PER_MESSAGE) return match;
    const emoji = NAMES[ALIASES[name] || name];
    if (!emoji) return match;
    used++;
    return emoji;
  });
  return out;
}

// 分类速查表：按场景分组告诉模型「什么心情用什么表情」，比一长串没有说明的 emoji 好用得多。
export const EMOJI_GUIDE = Object.entries(CATALOG)
  .map(([group, items]) => {
    const seen = new Set();
    const parts = [];
    for (const [name, emoji] of Object.entries(items)) {
      if (seen.has(emoji)) continue;
      seen.add(emoji);
      parts.push(`${emoji}${name}`);
    }
    return `【${group}】${parts.join(' ')}`;
  })
  .join(' ');

// 全部可用 emoji（按分类顺序，不做去重截断）。
export const EMOJI_HINT = Object.values(CATALOG)
  .flatMap((items) => Object.values(items))
  .filter((emoji, index, all) => all.indexOf(emoji) === index)
  .join(' ');

